<?php

namespace Database\Seeders;

use Illuminate\Database\Console\Seeds\WithoutModelEvents;
use Illuminate\Database\Seeder;

class DatabaseSeeder extends Seeder
{
    use WithoutModelEvents;

    public function run(): void
    {
        /*
        |--------------------------------------------------------------------------
        | 1) إعداد النظام الأساسي
        |--------------------------------------------------------------------------
        | الشركة، الفرع، الصلاحيات، الأدوار، مستخدم Master، ومالك الشركة.
        */
        $this->call([
            SystemSetupSeeder::class,
        ]);

        /*
        |--------------------------------------------------------------------------
        | 2) إعدادات الحسابات ودليل الحسابات
        |--------------------------------------------------------------------------
        */
        $this->call([
            AccountSettingSeeder::class,
            ChartOfAccountsSeeder::class,
        ]);

        /*
        |--------------------------------------------------------------------------
        | 3) تسلسل أرقام المستندات
        |--------------------------------------------------------------------------
        */
        $this->call([
            DocumentSequenceSeeder::class,
        ]);

        /*
        |--------------------------------------------------------------------------
        | 4) البيانات الأساسية والتشغيلية
        |--------------------------------------------------------------------------
        */
        $this->call([
            MasterDataSeeder::class,
            DefaultOperationalDataSeeder::class,
        ]);

        /*
        |--------------------------------------------------------------------------
        | 5) إعداد الترخيص
        |--------------------------------------------------------------------------
        */
        $this->call([
            LicenseSettingSeeder::class,
        ]);
    }
}